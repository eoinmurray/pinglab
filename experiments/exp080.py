ARTIFACTS, FIGURES = artifacts_and_figures(SLUG)
SMOKE = os.environ.get("PINGLAB_SMOKE") == "1"
MNIST_ROOT = Path(os.environ.get("PINGLAB_DATA_ROOT", "/tmp/mnist"))

PRESENTATION_MS = 200.0
DT_MS = 0.1
N_TIMESTEPS = int(round(PRESENTATION_MS / DT_MS))
PROBE_US = 1.2
RATES_HZ = (0.1, 0.25, 0.5, 1.0, 2.0, 5.0, 10.0, 25.0)
SEEDS = (42, 43, 44)
TRAIN_COUNT = 100 if SMOKE else 20_000
VALIDATION_COUNT = 50 if SMOKE else 5_000
TEST_COUNT = 50 if SMOKE else 5_000
EPOCHS_STANDARD = 50
EPOCHS = 2 if SMOKE else EPOCHS_STANDARD
BATCH_SIZE = 256
HIDDEN_UNITS = 1024
LEARNING_RATE = 0.001
CHANCE_ACCURACY = 0.10
USEFUL_ACCURACY = 0.50

PARAMETERS = {
    "C_m_nF": 1.0,
    "g_L_uS": 0.05,
    "E_L_mV": -65.0,
    "E_e_mV": 0.0,
    "tau_ampa_ms": 2.0,
}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def stable_seed(*parts: int) -> int:
    digest = hashlib.sha256(
        ":".join(str(part) for part in (80, *parts)).encode()
    ).digest()
    return int.from_bytes(digest[:8], "little") & ((1 << 63) - 1)


def torch_device() -> Any:
    import torch

    requested = os.environ.get("EXP080_DEVICE", "auto")
    if requested != "auto":
        return torch.device(requested)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def load_mnist_training() -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    from torchvision.datasets import MNIST

    dataset = MNIST(root=MNIST_ROOT, train=True, download=True)
    images = dataset.data.numpy().astype(np.uint8, copy=False)
    labels = dataset.targets.numpy().astype(np.int64, copy=False)
    if images.shape != (60_000, 28, 28) or labels.shape != (60_000,):
        raise RuntimeError(f"unexpected MNIST training contract: {images.shape}")
    return (
        images,
        labels,
        {
            "source": "torchvision.datasets.MNIST official training partition",
            "image_shape": list(images.shape),
            "label_shape": list(labels.shape),
            "raw_sha256": {
                path.name: sha256_file(path)
                for path in sorted(Path(dataset.raw_folder).glob("train-*-ubyte"))
            },
        },
    )


def load_mnist_test() -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    from torchvision.datasets import MNIST

    dataset = MNIST(root=MNIST_ROOT, train=False, download=True)
    images = dataset.data.numpy().astype(np.uint8, copy=False)[:TEST_COUNT]
    labels = dataset.targets.numpy().astype(np.int64, copy=False)[:TEST_COUNT]
    return (
        images,
        labels,
        {
            "source": "first 5000 images of the official MNIST test partition",
            "image_shape": list(images.shape),
            "label_shape": list(labels.shape),
            "raw_sha256": {
                path.name: sha256_file(path)
                for path in sorted(Path(dataset.raw_folder).glob("t10k-*-ubyte"))
            },
        },
    )


def direct_features(
    images_uint8: Any,
    rates_hz: Any,
    generator: Any,
) -> Any:
    """Direct decay-then-add AMPA and exponential membrane simulation."""
    import torch

    images = images_uint8.to(dtype=torch.float32).reshape(-1, 784) / 255.0
    rates = rates_hz.to(device=images.device, dtype=torch.float32).reshape(-1, 1)
    probability = images * rates * DT_MS / 1000.0
    if bool(torch.any(probability > 1.0)):
        raise ValueError("Bernoulli event probability exceeds one")
    conductance = torch.zeros_like(images)
    voltage = torch.full_like(images, PARAMETERS["E_L_mV"])
    feature_sum = torch.zeros_like(images)
    ampa_decay = math.exp(-DT_MS / PARAMETERS["tau_ampa_ms"])
    for _ in range(N_TIMESTEPS):
        events = (
            torch.rand(
                images.shape,
                device=images.device,
                dtype=images.dtype,
                generator=generator,
            )
            < probability
        )
        conductance = conductance * ampa_decay + PROBE_US * events
        total_g = PARAMETERS["g_L_uS"] + conductance
        equilibrium = (
            PARAMETERS["g_L_uS"] * PARAMETERS["E_L_mV"]
            + conductance * PARAMETERS["E_e_mV"]
        ) / total_g
        voltage = equilibrium + (voltage - equilibrium) * torch.exp(
            -DT_MS * total_g / PARAMETERS["C_m_nF"]
        )
        feature_sum += voltage - PARAMETERS["E_L_mV"]
    return feature_sum / N_TIMESTEPS


def probe_single_spike(spike_time_ms: float) -> float:
    conductance = 0.0
    voltage = PARAMETERS["E_L_mV"]
    total = 0.0
    event_step = int(round(spike_time_ms / DT_MS))
    decay = math.exp(-DT_MS / PARAMETERS["tau_ampa_ms"])
    for step in range(N_TIMESTEPS):
        conductance = conductance * decay + (PROBE_US if step == event_step else 0.0)
        total_g = PARAMETERS["g_L_uS"] + conductance
        equilibrium = (
            PARAMETERS["g_L_uS"] * PARAMETERS["E_L_mV"]
            + conductance * PARAMETERS["E_e_mV"]
        ) / total_g
        voltage = equilibrium + (voltage - equilibrium) * math.exp(
            -DT_MS * total_g / PARAMETERS["C_m_nF"]
        )
        total += voltage - PARAMETERS["E_L_mV"]
    return total / N_TIMESTEPS


def validate_simulator() -> dict[str, Any]:
    decay = math.exp(-DT_MS / PARAMETERS["tau_ampa_ms"])
    early = probe_single_spike(20.0)
    late = probe_single_spike(180.0)
    checks = {
        "ampa_decay_in_unit_interval": 0.0 < decay < 1.0,
        "early_spike_exceeds_late_spike": early > late > 0.0,
        "zero_input_feature_is_zero_by_construction": True,
        "timestep_count_exact": N_TIMESTEPS == 2000,
    }
    if not all(checks.values()):
        raise RuntimeError(f"simulator validation failed: {checks}")
    return {"checks": checks, "early_spike_mV": early, "late_spike_mV": late}


def make_model(device: Any, seed: int) -> Any:
    import torch

    torch.manual_seed(seed)
    model = torch.nn.Sequential(
        torch.nn.Linear(784, HIDDEN_UNITS),
        torch.nn.ReLU(),
        torch.nn.Linear(HIDDEN_UNITS, 10),
    )
    return model.to(device)


def batches(indices: np.ndarray, seed: int, shuffle: bool) -> list[np.ndarray]:
    order = np.asarray(indices, dtype=np.int64).copy()
    if shuffle:
        np.random.default_rng(seed).shuffle(order)
    return [
        order[start : start + BATCH_SIZE] for start in range(0, len(order), BATCH_SIZE)
    ]


def train_seed(images: np.ndarray, labels: np.ndarray, seed: int) -> dict[str, Any]:
    import torch

    device = torch_device()
    model = make_model(device, seed)
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)
    generator = torch.Generator(device=device)
    train_indices = np.arange(TRAIN_COUNT)
    validation_indices = np.arange(TRAIN_COUNT, TRAIN_COUNT + VALIDATION_COUNT)
    history: list[dict[str, Any]] = []
    best_accuracy = -math.inf
    best_epoch = 0
    best_state: dict[str, Any] | None = None
    started = time.perf_counter()

    for epoch in range(1, EPOCHS + 1):
        model.train()
        train_correct = 0
        train_seen = 0
        rate_rng = np.random.default_rng(stable_seed(seed, epoch, 1))
        generator.manual_seed(stable_seed(seed, epoch, 2))
        for indices in batches(train_indices, stable_seed(seed, epoch, 3), True):
            rates = np.asarray(RATES_HZ)[
                rate_rng.integers(0, len(RATES_HZ), len(indices))
            ]
            batch_images = torch.as_tensor(images[indices], device=device)
            batch_labels = torch.as_tensor(labels[indices], device=device)
            features = direct_features(
                batch_images,
                torch.as_tensor(rates, device=device, dtype=torch.float32),
                generator,
            )
            optimizer.zero_grad(set_to_none=True)
            logits = model(features)
            loss = torch.nn.functional.cross_entropy(logits, batch_labels)
            loss.backward()
            optimizer.step()
            train_correct += int((logits.argmax(1) == batch_labels).sum().item())
            train_seen += len(indices)

        model.eval()
        validation_correct = 0
        validation_seen = 0
        rate_rng = np.random.default_rng(stable_seed(seed, epoch, 4))
        generator.manual_seed(stable_seed(seed, epoch, 5))
        with torch.no_grad():
            for indices in batches(validation_indices, 0, False):
                rates = np.asarray(RATES_HZ)[
                    rate_rng.integers(0, len(RATES_HZ), len(indices))
                ]
                features = direct_features(
                    torch.as_tensor(images[indices], device=device),
                    torch.as_tensor(rates, device=device, dtype=torch.float32),
                    generator,
                )
                batch_labels = torch.as_tensor(labels[indices], device=device)
                validation_correct += int(
                    (model(features).argmax(1) == batch_labels).sum().item()
                )
                validation_seen += len(indices)
        validation_accuracy = validation_correct / validation_seen
        history.append(
            {
                "epoch": epoch,
                "train_accuracy": train_correct / train_seen,
                "validation_accuracy": validation_accuracy,
            }
        )
        if validation_accuracy > best_accuracy:
            best_accuracy = validation_accuracy
            best_epoch = epoch
            best_state = {
                name: value.detach().cpu() for name, value in model.state_dict().items()
            }
        print(
            f"exp080 seed={seed} epoch={epoch}/{EPOCHS} val={validation_accuracy:.4f}",
            flush=True,
        )

    if best_state is None:
        raise RuntimeError("training produced no checkpoint")
    directory = ARTIFACTS / "models" / f"seed-{seed}"
    directory.mkdir(parents=True, exist_ok=True)
    checkpoint = directory / "decoder.pt"
    torch.save({"state_dict": best_state, "seed": seed}, checkpoint)
    record = {
        "seed": seed,
        "device": str(device),
        "runtime_s": time.perf_counter() - started,
        "selected_epoch": best_epoch,
        "selected_validation_accuracy": best_accuracy,
        "history": history,
        "checkpoint": str(checkpoint.relative_to(ARTIFACTS)),
        "checkpoint_sha256": sha256_file(checkpoint),
    }
    (directory / "training.json").write_text(json.dumps(record, indent=2) + "\n")
    return record


def plot_training(records: list[dict[str, Any]]) -> None:
    theme.apply()
    fig, axis = plt.subplots(figsize=(5.1, 3.1), constrained_layout=True)
    for record in records:
        axis.plot(
            [row["epoch"] for row in record["history"]],
            [row["validation_accuracy"] for row in record["history"]],
            label=f"Seed {record['seed']}",
        )
    axis.set(xlabel="Epoch", ylabel="Mixed-rate validation accuracy", ylim=(0, 1))
    axis.spines[["top", "right"]].set_visible(False)
    axis.legend(frameon=False)
    fig.savefig(FIGURES / "training_history.svg", metadata={"Date": None})
    plt.close(fig)


def load_models(records: list[dict[str, Any]], device: Any) -> list[Any]:
    import torch

    models = []
    for item in records:
        path = ARTIFACTS / item["checkpoint"]
        if sha256_file(path) != item["checkpoint_sha256"]:
            raise RuntimeError(f"checkpoint hash mismatch: {path}")
        model = make_model(device, int(item["seed"]))
        model.load_state_dict(
            torch.load(path, map_location=device, weights_only=True)["state_dict"]
        )
        model.eval()
        models.append(model)
    return models


def evaluate(records: list[dict[str, Any]]) -> tuple[dict[str, Any], np.ndarray]:
    import torch

    images, labels, dataset = load_mnist_test()
    device = torch_device()
    models = load_models(records, device)
    correctness = np.empty((len(RATES_HZ), len(SEEDS), TEST_COUNT), dtype=np.bool_)
    labels_tensor = torch.as_tensor(labels, device=device)
    started = time.perf_counter()
    for rate_index, rate in enumerate(RATES_HZ):
        for start in range(0, TEST_COUNT, BATCH_SIZE):
            stop = min(start + BATCH_SIZE, TEST_COUNT)
            generator = torch.Generator(device=device).manual_seed(
                stable_seed(9, rate_index, start)
            )
            features = direct_features(
                torch.as_tensor(images[start:stop], device=device),
                torch.full((stop - start,), rate, device=device),
                generator,
            )
            with torch.no_grad():
                for seed_index, model in enumerate(models):
                    correctness[rate_index, seed_index, start:stop] = (
                        (model(features).argmax(1) == labels_tensor[start:stop])
                        .cpu()
                        .numpy()
                    )
        print(f"exp080 held-out rate={rate:g} Hz", flush=True)
    arrays_path = ARTIFACTS / "held_out_correctness.npz"
    np.savez_compressed(
        arrays_path,
        correctness=correctness,
        rates_hz=np.asarray(RATES_HZ),
        seeds=np.asarray(SEEDS),
        labels=labels,
    )
    return {
        "device": str(device),
        "runtime_s": time.perf_counter() - started,
        "dataset": dataset,
        "arrays_sha256": sha256_file(arrays_path),
    }, correctness


def analyze(correctness: np.ndarray) -> dict[str, Any]:
    rows = []
    for rate_index, rate in enumerate(RATES_HZ):
        per_seed = correctness[rate_index].mean(axis=1)
        rows.append(
            {
                "rate_hz": rate,
                "accuracy": float(per_seed.mean()),
                "minimum_seed_accuracy": float(per_seed.min()),
                "maximum_seed_accuracy": float(per_seed.max()),
                "per_seed_accuracy": per_seed.tolist(),
            }
        )
    floor = next(
        (
            row["rate_hz"]
            for row in rows
            if row["minimum_seed_accuracy"] >= USEFUL_ACCURACY
        ),
        None,
    )
    decision = {
        "criterion_crossed": floor is not None,
        "r_train_hz": floor,
        "recommendation": {"floor_hz": floor, "ceiling_hz": max(RATES_HZ)},
        "rows": rows,
    }
    (FIGURES / "decision.json").write_text(json.dumps(decision, indent=2) + "\n")
    return decision


def plot_psychometric(decision: dict[str, Any]) -> None:
    theme.apply()
    rows = decision["rows"]
    rates = np.asarray([row["rate_hz"] for row in rows])
    accuracy = np.asarray([row["accuracy"] for row in rows])
    lower = np.asarray([row["minimum_seed_accuracy"] for row in rows])
    upper = np.asarray([row["maximum_seed_accuracy"] for row in rows])
    fig, axis = plt.subplots(figsize=(5.1, 3.2), constrained_layout=True)
    axis.plot(rates, accuracy, color=theme.INK_BLACK, marker="o")
    axis.fill_between(
        rates, lower, upper, color=theme.INK_BLACK, alpha=0.14, linewidth=0
    )
    axis.axhline(CHANCE_ACCURACY, color="#777777", linestyle=":", label="Chance")
    axis.axhline(
        USEFUL_ACCURACY, color="#777777", linestyle="--", label="Practical criterion"
    )
    if decision["criterion_crossed"]:
        axis.axvline(
            decision["r_train_hz"],
            color=theme.DEEP_RED,
            linewidth=1.0,
            label="Selected floor",
        )
    axis.set_xscale("log")
    axis.set_xticks(RATES_HZ)
    axis.set_xticklabels([f"{rate:g}" for rate in RATES_HZ])
    axis.set(
        xlabel="Maximum-pixel encoding rate (Hz)",
        ylabel="Held-out accuracy",
        ylim=(0, 1),
    )
    axis.spines[["top", "right"]].set_visible(False)
    axis.legend(frameon=False, fontsize=7)
    fig.savefig(FIGURES / "psychometric.svg", metadata={"Date": None})
    plt.close(fig)


def plot_feature_images(images: np.ndarray) -> None:
    import torch

    device = torch_device()
    rates = (0.5, 5.0, 25.0)
    generator = torch.Generator(device=device).manual_seed(stable_seed(11))
    selected = torch.as_tensor(
        np.repeat(images[[0]], len(rates), axis=0), device=device
    )
    features = (
        direct_features(
            selected,
            torch.as_tensor(rates, device=device, dtype=torch.float32),
            generator,
        )
        .cpu()
        .numpy()
    )
    theme.apply()
    fig, axes = plt.subplots(1, 4, figsize=(6.5, 2.0), constrained_layout=True)
    axes[0].imshow(images[0], cmap="gray", vmin=0, vmax=255)
    axes[0].set_title("Input image")
    for axis, feature, rate in zip(axes[1:], features, rates, strict=True):
        axis.imshow(feature.reshape(28, 28), cmap="magma", vmin=0, vmax=65)
        axis.set_title(f"{rate:g} Hz")
    for axis in axes:
        axis.set_xticks([])
        axis.set_yticks([])
    fig.savefig(FIGURES / "feature_images.png", dpi=240)
    plt.close(fig)


@preserve_active_view(SLUG)
def main() -> None:
    started = time.perf_counter()
    FIGURES.mkdir(parents=True, exist_ok=True)
    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    validation = validate_simulator()
    images, labels, training_dataset = load_mnist_training()
    plot_feature_images(images)
    records = [train_seed(images, labels, seed) for seed in SEEDS]
    plot_training(records)
    evaluation, correctness = evaluate(records)
    decision = analyze(correctness)
    plot_psychometric(decision)
    numbers = {
        "status": "complete",
        "purpose": "empirically select the later variable-rate PING input range",
        "parameters": {
            "presentation_ms": PRESENTATION_MS,
            "dt_ms": DT_MS,
            "probe_uS": PROBE_US,
            "rates_hz": list(RATES_HZ),
            "seeds": list(SEEDS),
            "train_count": TRAIN_COUNT,
            "validation_count": VALIDATION_COUNT,
            "test_count": TEST_COUNT,
            "epochs": EPOCHS,
            "useful_accuracy": USEFUL_ACCURACY,
        },
        "simulator_validation": validation,
        "training_dataset": training_dataset,
        "training": records,
        "evaluation": evaluation,
        "decision": decision,
        "runtime_s": time.perf_counter() - started,
        "environment": {
            "python": platform.python_version(),
            "numpy": np.__version__,
            "device": str(torch_device()),
        },
    }
    run_id = next_run_id(SLUG)
    write_numbers(
        FIGURES,
        run_id=run_id,
        duration_s=numbers["runtime_s"],
        payload=numbers,
    )
    (ARTIFACTS / "reproducer.json").write_text(
        json.dumps({"command": "uv run python experiments/exp080.py"}, indent=2) + "\n"
    )
    (FIGURES / "_run.txt").write_text(f"{int(run_id.lstrip('r'))}\n")
    if decision["criterion_crossed"]:
        summary = f"selected {decision['r_train_hz']:g}--{max(RATES_HZ):g} Hz"
    else:
        summary = "practical criterion not crossed within tested rates"
    print(f"exp080 complete: {summary}", flush=True)
    finalize_prepared_run(SLUG, run_id)


if __name__ == "__main__":
    main()
